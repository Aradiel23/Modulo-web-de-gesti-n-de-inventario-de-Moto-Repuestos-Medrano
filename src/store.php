function referencias_motos_en_nombre(string $nombre, array $vehiculos): array {
    $texto = preg_replace('/[^A-Z0-9]+/', ' ', strtoupper($nombre)) ?? '';
    // Variantes de nombres encontrados en el catálogo impreso.
    $patrones = [
        'Honda|Biz 100'            => '/\bBIZ\s*100(?:I)?\b/',
        'Honda|Biz 125'            => '/\bBIZ\s*125\b/',
        'Honda|Bros 125'           => '/\bBROS\s*125\b/',
        'Honda|Bros 150'           => '/\bBROS\s*150\b/',
        'Honda|Bros 160'           => '/\bBROS\s*160\b/',
        'Honda|CG Titan 150'       => '/\bTITAN\s*150\b/',
        'Honda|CG Titan 160'       => '/\bTITAN\s*160\b/',
        'Honda|XR 150L'            => '/\bXR\s*150\s*L?\b/',
        'Honda|XR 190L'            => '/\bXR\s*190\s*L?\b/',
        'Honda|XR 200'             => '/\bXR\s*200\b/',
        'Honda|XRE 300'            => '/\bXRE\s*300\b/',
        'Honda|CRF 230F'           => '/\bCRF\s*230\s*F?\b/',
        'Honda|CRF 250F'           => '/\bCRF\s*250\s*F\b/',
        'Honda|Pop 110'            => '/\bPOP\s*110(?:I)?\b/',
        'Honda|Wave 110S'          => '/\bWAVE\s*110\s*S?\b/',
        'Honda|Navi 110'           => '/\bNAVI\s*110\b/',
        'Honda|CG 125'             => '/\bCG\s*125\b/',
        'Honda|CGL 125'            => '/\bCGL\s*125\b/',
        'Yamaha|YBR 125'           => '/\bYBR\s*125\b/',
        'Yamaha|XTZ 125'           => '/\bXTZ\s*125\b/',
        'Yamaha|XTZ 150 Crosser'   => '/\b(?:XTZ\s*150(?:\s*CROSSER)?|CROSSER\s*150)\b/',
        'Yamaha|XTZ 250 Lander'    => '/\bXTZ\s*250\b/',
        'Yamaha|Crypton 115'       => '/\bCRYPTON\s*115\b/',
    ];

    $encontrados = [];
    foreach ($vehiculos as $moto) {
        $clave = ($moto['marca'] ?? '') . '|' . ($moto['modelo'] ?? '');
        if (isset($patrones[$clave]) && preg_match($patrones[$clave], $texto) === 1) {
            $encontrados[] = (string)$moto['id'];
        }
    }
    return $encontrados;
}

function ubicacion_demo_para_indice(int $indice): string {
    $deposito = chr(ord('A') + ($indice % 26));
    $estante = (($indice * 7) % 40) + 1;
    return 'Depósito ' . $deposito . ' - Estante ' . str_pad((string)$estante, 2, '0', STR_PAD_LEFT);
}

function preparar_catalogo_demostracion(array $catalogo): array {
    foreach ($catalogo['productos'] as $i => &$producto) {
        $producto['ubicacion'] = ubicacion_demo_para_indice($i);
        $producto['ubicacion_demo'] = true;
        $ids = referencias_motos_en_nombre((string)$producto['nombre'], $catalogo['vehiculos']);
        $producto['compatibles'] = $ids;
        // Indica al usuario que es una asociación por nombre, NO validación técnica.
        $producto['compatibles_demo'] = $ids;
        $producto['compatibilidad_demo'] = count($ids) > 0;
    }
    unset($producto);
    $catalogo['_catalogo_inicial_instalado'] = 'MEDRANO-MOTOS-UBICACIONES-2026-10-31-v3';
    $catalogo['datos_simulados'] = true;
    $catalogo['descripcion_demo'] = 'Stock, ubicaciones y relaciones por coincidencia textual simulados para presentación académica. No son existencias, posiciones ni compatibilidades verificadas por Moto Repuestos Medrano.';
    $catalogo['meta_simulacion'] = [
        'ubicaciones' => 'Depósitos A-Z y estantes 01-40 asignados solo para presentación.',
        'compatibilidad' => 'Asociación demostrativa basada únicamente en nombre y modelo explícitos en el repuesto; no es comprobación mecánica.',
        'filtro' => 'Para filtrar por moto se utiliza el campo compatibles con IDs de vehiculos.',
    ];
    return $catalogo;
}

/**
 * Crea data/inventario.json al primer uso si no existe.
 * Si ya existía, añade modelos nuevos y los productos que falten.
 * Los stocks de demostración se aplican SOLO a productos importados sin
 * movimientos y con stock=0 no confirmado; no sobrescribe conteos reales.
 */
function init_database(): void {
    static $comprobados = [];
    $path = database_file();
    if (isset($comprobados[$path])) return;

    $folder = dirname($path);
    if (!is_dir($folder) && !mkdir($folder, 0775, true) && !is_dir($folder)) {
        throw new RuntimeException('No se pudo crear la carpeta del inventario.');
    }
    $catalogo = demo_seed();
    $marca = 'MEDRANO-MOTOS-UBICACIONES-2026-10-31-v3';

    // Si borraste inventario.json, se genera automáticamente con datos.
    $nuevo = @fopen($path, 'x');
    if ($nuevo !== false) {
        try {
            if (!flock($nuevo, LOCK_EX)) throw new RuntimeException('No se pudo bloquear el inventario nuevo.');
            $texto = json_encode($catalogo, JSON_PRETTY_PRINT | JSON_UNESCAPED_UNICODE | JSON_THROW_ON_ERROR);
            if (fwrite($nuevo, $texto) !== strlen($texto)) throw new RuntimeException('No se pudo guardar el inventario inicial.');
            fflush($nuevo);
            $comprobados[$path] = true;
        } finally { flock($nuevo, LOCK_UN); fclose($nuevo); }
        return;
    }

    $fp = @fopen($path, 'c+');
    if ($fp === false) throw new RuntimeException('No se pudo abrir inventario.json.');
    try {
        if (!flock($fp, LOCK_EX)) throw new RuntimeException('No se pudo bloquear el inventario.');
        rewind($fp);
        $contenido = stream_get_contents($fp);
        if ($contenido === false || trim($contenido) === '') {
            throw new RuntimeException('inventario.json existe pero está vacío; restáuralo desde una copia.');
        }
        $actual = json_decode($contenido, true, 512, JSON_THROW_ON_ERROR);
        if (!is_array($actual) || !isset($actual['productos']) || !is_array($actual['productos'])) {
            throw new RuntimeException('inventario.json tiene una estructura inválida.');
        }
        if (($actual['_catalogo_inicial_instalado'] ?? '') === $marca) {
            $comprobados[$path] = true;
            return;
        }

        $codigos = [];
        foreach ($actual['productos'] as $i=>$p) {
            if (isset($p['sku'])) $codigos[(string)$p['sku']] = $i;
        }
        $modificados = [];
        foreach (($actual['movimientos'] ?? []) as $m) {
            if (isset($m['sku'])) $modificados[(string)$m['sku']] = true;
        }
        foreach ($catalogo['productos'] as $p) {
            $sku = (string)$p['sku'];
            if (!isset($codigos[$sku])) {
                $actual['productos'][] = $p;
                $codigos[$sku] = count($actual['productos']) - 1;
            } else {
                $idx = $codigos[$sku];
                $existing = &$actual['productos'][$idx];
               
                if (($existing['origen'] ?? '') === 'CATALOGO MEDRANO 17-08-2026'
                    && !($existing['stock_confirmado'] ?? false)
                    && !isset($modificados[$sku])
                    && (int)($existing['stock'] ?? 0) === 0
                    && !($existing['stock_demo'] ?? false)) {
                    $existing['stock'] = $p['stock'];
                    $existing['minimo'] = $p['minimo'];
                    $existing['stock_demo'] = true;
                    if (empty($existing['ubicacion'])) $existing['ubicacion'] = $p['ubicacion'];
                }
                
                if (($existing['origen'] ?? '') === 'CATALOGO MEDRANO 17-08-2026'
                    && (trim((string)($existing['ubicacion'] ?? '')) === ''
                        || str_starts_with((string)$existing['ubicacion'], 'Demo-'))) {
                    $existing['ubicacion'] = $p['ubicacion'];
                    $existing['ubicacion_demo'] = true;
                }
                
                if (($existing['origen'] ?? '') === 'CATALOGO MEDRANO 17-08-2026'
                    && empty($existing['compatibles']) && !empty($p['compatibles'])) {
                    $existing['compatibles'] = $p['compatibles'];
                    $existing['compatibles_demo'] = $p['compatibles'];
                    $existing['compatibilidad_demo'] = true;
                }
                unset($existing);
            }
        }

        if (!isset($actual['vehiculos']) || !is_array($actual['vehiculos'])) $actual['vehiculos'] = [];
        $ids = [];
        foreach ($actual['vehiculos'] as $idx=>$vehiculo) {
            if (isset($vehiculo['id'])) $ids[(string)$vehiculo['id']] = $idx;
        }
        foreach ($catalogo['vehiculos'] as $vehiculo) {
            $id = (string)$vehiculo['id'];
            if (!isset($ids[$id])) {
                $actual['vehiculos'][] = $vehiculo;
                $ids[$id] = count($actual['vehiculos']) - 1;
            } else {
                // Completa cilindrada/año sin cambiar las relaciones existentes.
                $idx = $ids[$id];
                foreach (['cilindrada','anio','anio_referencial','fuente_modelo'] as $field) {
                    if (!isset($actual['vehiculos'][$idx][$field])) $actual['vehiculos'][$idx][$field] = $vehiculo[$field];
                }
            }
        }
        if (!isset($actual['movimientos']) || !is_array($actual['movimientos'])) $actual['movimientos'] = [];
        if (!isset($actual['catalogo_fuente'])) $actual['catalogo_fuente'] = $catalogo['catalogo_fuente'];
        $actual['meta_vehiculos'] = $catalogo['meta_vehiculos'];
        $actual['_catalogo_inicial_instalado'] = $marca;
        
        if (!isset($actual['datos_simulados'])) $actual['datos_simulados'] = true;
        $actual['descripcion_demo'] = $catalogo['descripcion_demo'];
        $actual['meta_simulacion'] = $catalogo['meta_simulacion'];

        $texto = json_encode($actual, JSON_PRETTY_PRINT | JSON_UNESCAPED_UNICODE | JSON_THROW_ON_ERROR);
        rewind($fp);
        if (!ftruncate($fp, 0) || fwrite($fp, $texto) !== strlen($texto)) throw new RuntimeException('No se pudo guardar el catálogo actualizado.');
        fflush($fp);
        $comprobados[$path] = true;
    } finally { flock($fp, LOCK_UN); fclose($fp); }
}


function read_database(): array {
    init_database();
    return (new InventarioRepository(database_file()))->leer();
}
function update_database(callable $change): void {
    init_database();
    (new InventarioRepository(database_file()))->modificar($change);
}
function find_product(array $productos, string $sku): ?array {
    foreach ($productos as $registro) {
        if (($registro['sku'] ?? '') === $sku) return Producto::desdeArray($registro)->aArray();
    }
    return null;
}
function find_vehicle(array $vehiculos, string $id): ?array {
    foreach ($vehiculos as $registro) {
        if (($registro['id'] ?? '') === $id) return Motocicleta::desdeArray($registro)->aArray();
    }
    return null;
}
// Valida SKU y campos antes de crear o actualizar un repuesto.
// No modifica el stock: eso solo ocurre mediante save_movement().
function save_product(array $input): void {
    $sku = strtoupper(trim((string)($input['sku'] ?? '')));
    $original = trim((string)($input['original'] ?? ''));
    $name = trim((string)($input['nombre'] ?? ''));
    $category = trim((string)($input['categoria'] ?? ''));
    $brand = trim((string)($input['marca'] ?? ''));
    $location = trim((string)($input['ubicacion'] ?? ''));
    $priceString = (string)($input['precio'] ?? '');
    $minString = (string)($input['minimo'] ?? '');
    if (!preg_match('/^[A-Z0-9-]{3,30}$/', $sku)) throw new DomainException('El código SKU debe tener 3 a 30 caracteres: letras, números o guiones.');
    if ($name === '' || $category === '') throw new DomainException('Nombre y categoría son obligatorios.');
    if (strlen($name) > 120 || strlen($category) > 60 || strlen($brand) > 70 || strlen($location) > 60) throw new DomainException('Uno de los campos es demasiado largo.');
    if (!is_numeric($priceString) || (float)$priceString < 0 || (float)$priceString > 9999999) throw new DomainException('El precio debe ser un número positivo o cero.');
    if (filter_var($minString, FILTER_VALIDATE_INT) === false || (int)$minString < 0) throw new DomainException('El stock mínimo debe ser un entero positivo o cero.');
    $compat = array_values(array_unique(array_filter((array)($input['compatibles'] ?? []), 'is_string')));
    $equiv = array_values(array_unique(array_filter((array)($input['equivalentes'] ?? []), 'is_string')));
    update_database(function (&$db) use ($sku,$original,$name,$category,$brand,$location,$priceString,$minString,$compat,$equiv) {
        $existing = find_product($db['productos'], $sku);
        if ($original !== '' && $original !== $sku) throw new DomainException('El código SKU no se puede modificar.');
        if ($original === '' && $existing) throw new DomainException('Ya existe un producto con este código SKU.');
        if ($original !== '' && !$existing) throw new DomainException('El producto que intentas editar no existe.');
        foreach ($compat as $id) if (!find_vehicle($db['vehiculos'], $id)) throw new DomainException('Se seleccionó una motocicleta desconocida.');
        foreach ($equiv as $code) {
            if ($code === $sku || !find_product($db['productos'], $code)) throw new DomainException('La equivalencia seleccionada es inválida.');
        }
        // Mantiene metadatos del catálogo (unidad, origen, stock_confirmado, etc.).
        $p = array_replace($existing ?? [], [
            'sku'=>$sku,'nombre'=>$name,'categoria'=>$category,'marca'=>$brand,
            'precio'=>round((float)$priceString, 2),'stock'=>$existing['stock'] ?? 0,
            'minimo'=>(int)$minString,'ubicacion'=>$location,'compatibles'=>$compat,
            'equivalentes'=>$equiv,'activo'=>$existing['activo'] ?? true
        ]);
        // Diferencia las selecciones y ubicaciones manuales de los ejemplos iniciales.
        if ($existing && $location !== (string)($existing['ubicacion'] ?? '')) {
            $p['ubicacion_demo'] = false;
        }
        if ($existing && $compat !== ($existing['compatibles'] ?? [])) {
            $p['compatibilidad_demo'] = false;
            $p['compatibles_demo'] = [];
        }
        // Un precio editado por el usuario deja de figurar como pendiente.
        $p['precio_pendiente'] = false;
        // El modelo valida la entidad antes de almacenarla.
        $p = Producto::desdeArray($p)->aArray();
        if ($existing) {
            foreach ($db['productos'] as &$row) if ($row['sku'] === $sku) { $row = $p; break; }
            unset($row);
        } else $db['productos'][] = $p;
    });
}
// Permite desactivar productos sin borrar el historial de inventario.
function toggle_product(string $sku): void {
    update_database(function (&$db) use ($sku) {
        foreach ($db['productos'] as &$product) {
            if ($product['sku'] === $sku) {
                $product = Producto::desdeArray($product)->alternarActivo()->aArray();
                return;
            }
        }
        throw new DomainException('Producto no encontrado.');
    });
}
// Registro de entrada/salida con validaciones y trazabilidad.
// La operación se ejecuta bajo bloqueo exclusivo de archivo (flock).
function save_movement(array $input): array {
    $sku = strtoupper(trim((string)($input['sku'] ?? '')));
    $type = (string)($input['tipo'] ?? '');
    $qtyString = (string)($input['cantidad'] ?? '');
    $reason = trim((string)($input['motivo'] ?? ''));
    if (!in_array($type, ['entrada','salida'], true)) throw new DomainException('Tipo de movimiento inválido.');
    if (filter_var($qtyString, FILTER_VALIDATE_INT) === false || (int)$qtyString <= 0 || (int)$qtyString > 1000000) throw new DomainException('La cantidad debe ser un entero mayor a cero.');
    if ($reason === '' || strlen($reason) > 180) throw new DomainException('Debes registrar un motivo de hasta 180 caracteres.');
    $result = [];
    update_database(function (&$db) use ($sku,$type,$qtyString,$reason,&$result) {
        foreach ($db['productos'] as &$product) {
            if ($product['sku'] !== $sku) continue;
            $modeloAnterior = Producto::desdeArray($product);
            $modeloNuevo = $modeloAnterior->aplicarMovimiento($type, (int)$qtyString);
            $product = $modeloNuevo->aArray();
            // El modelo Movimiento documenta y valida la transición de existencias.
            $movement = Movimiento::registrar(
                $modeloAnterior, $modeloNuevo, $type, (int)$qtyString, $reason
            )->aArray();
            array_unshift($db['movimientos'], $movement);
            $result = $movement;
            return;
        }
        unset($product);
        throw new DomainException('Producto no encontrado.');
    });
    return $result;
}
